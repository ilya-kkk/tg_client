#!/usr/bin/env bash
set -euo pipefail

REPO="/home/ilya/Desktop/tg_client"
PLAN_FILE="$REPO/multiakk_refactor.md"

PROMPT=$(cat << 'EOF'
Работай в репозитории `/home/ilya/Desktop/tg_client`.

ТВОЯ ЗАДАЧА ЗА ОДИН ЗАПУСК:
- Выполнить РОВНО ОДНУ следующую невыполненную задачу из файла `multiakk_refactor.md`.
- Отметить эту задачу в `multiakk_refactor.md` как выполненную.
- Сделать один осмысленный коммит на русском.
- Запушить изменения в текущую ветку.
- НИКАКИХ других задач в этом запуске не трогать.

ФАЙЛ С ПЛАНОМ:
- Используй файл `multiakk_refactor.md` в корне репозитория.
- ЗАГОЛОВКИ, начинающиеся с `#`, `##`, `###` и т.п., ИГНОРИРУЙ ПОЛНОСТЬЮ — они НЕ являются задачами.
- Считай задачей только строки списка, начинающиеся с `- ` (маркер списка), включая подзадачи.
- ВЫПОЛНЕННОЙ считается строка, которая начинается с `- [x] `.
- НЕВЫПОЛНЕННОЙ считается строка, которая:
  - начинается с `- `,
  - и при этом НЕ начинается с `- [x] `.

АЛГОРИТМ ВЫБОРА ЗАДАЧИ:
1. Прочитай `multiakk_refactor.md`.
2. Игнорируя все заголовки (`#`, `##`, `###` и т.п.), найди ПЕРВУЮ сверху строку, начинающуюся с `- `, которая ещё не помечена как `- [x] `.
3. Считай ЭТУ строку текущей задачей. Подпункты под ней (строки, идущие сразу после и логически относящиеся к ней) используй как детали, но выполненной помечай именно основную строку.

КАК ОТМЕЧАТЬ ЗАДАЧУ КАК ВЫПОЛНЕННУЮ:
- В `multiakk_refactor.md` замени у выбранной задачи начальный `- ` на `- [x] `.
- Пример: было
  - `- **Создать таблицу telegram_sessions в Supabase**`
  станет
  - `- [x] **Создать таблицу telegram_sessions в Supabase**`

ТРЕБОВАНИЯ К РЕАЛИЗАЦИИ:
- Реализуй задачу полноценно, а НЕ частично. Если задача большая, всё равно доведи её до разумно законченного состояния в рамках одного запуска.
- Вноси изменения только в те файлы, которые напрямую относятся к текущей задаче.
- Следи за тем, чтобы проект собирался и запускался (насколько это возможно в рамках задачи).
- Не рефакторь и не меняй API сверх того, что требуется задачей.

GIT-ШАГИ ДЛЯ КАЖДОГО ЗАПУСКА:
1. Выполни задачу в коде.
2. Обнови `multiakk_refactor.md`, пометив задачу как `- [x] ...`.
3. Посмотри `git status`, чтобы убедиться, какие файлы изменены.
4. Добавь в индекс только релевантные изменения (не добавляй `.env`, `pgdata`, `sessions`, кэш и временные файлы).
5. Сделай ОДИН коммит с кратким русским сообщением в повелительном наклонении, которое описывает суть задачи.
6. Выполни `git push` в текущую ветку.

ОГРАНИЧЕНИЯ:
- За один запуск НЕ переходи к следующей задаче даже если осталось время.
- Не меняй порядок задач в `multiakk_refactor.md`.
- Не переписывай формулировки задач, только добавляй `- [x] ` перед выполненными.

Суммируя:
Каждый раз, когда тебя запускают с этим промтом, ты:
1) берёшь первую сверху невыполненную строку-ЗАДАЧУ (начинается с `- `, не `- [x]`) из `multiakk_refactor.md`, игнорируя все заголовки,
2) выполняешь её в коде,
3) отмечаешь как `- [x]` в `multiakk_refactor.md`,
4) коммитишь изменения с русским осмысленным сообщением,
5) пушишь в репозиторий.
EOF
)

cd "$REPO"

echo "Старт цикла Codex по задачам из $PLAN_FILE"

while grep -E '^- ' "$PLAN_FILE" | grep -vq '^- \[x\] '; do
  echo "Есть невыполненные задачи, запускаю Codex..."
  codex exec --full-auto "$PROMPT"
  echo "Итерация Codex завершена, проверяю задачи..."
  sleep 2
done

echo "Все задачи из $PLAN_FILE помечены как выполненные."